// Regenerates src/icons.mjs from @phosphor-icons/core (MIT).
// Usage: node tools/vendor-icons.mjs <path-to-@phosphor-icons/core/assets>
import fs from 'node:fs';
import path from 'node:path';

const assets = process.argv[2];
if (!assets) throw new Error('Pass the path to @phosphor-icons/core/assets');

const regular = [
  'map-pin', 'envelope-simple', 'phone', 'instagram-logo', 'x-logo', 'snapchat-logo', 'tiktok-logo',
  'caret-down', 'caret-up', 'caret-left', 'caret-right', 'file-plus', 'list', 'x',
  'arrow-left', 'arrow-right', 'arrow-up-left', 'arrow-up-right', 'whatsapp-logo', 'headset', 'calendar-plus',
  'house-line', 'buildings', 'arrows-left-right', 'calendar-check', 'identification-card', 'check',
  'minus', 'plus', 'paper-plane-tilt', 'eye', 'compass', 'file-pdf', 'sliders-horizontal',
  'arrow-counter-clockwise', 'magnifying-glass', 'play-circle', 'check-circle', 'lock-simple'
];
const duotone = [
  'buildings', 'users-three', 'handshake', 'shield-check', 'seal-check', 'file-text', 'hand-heart',
  'house-line', 'arrows-left-right', 'calendar-check', 'identification-card', 'chats-circle', 'signature',
  'airplane-tilt', 'file-pdf', 'check-circle', 'headset', 'whatsapp-logo', 'phone', 'envelope-simple',
  'map-pin', 'clock', 'eye', 'medal', 'lightning', 'scales'
];

const inner = file => fs.readFileSync(file, 'utf8').replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
const out = { regular: {}, duotone: {} };
for (const n of regular) out.regular[n] = inner(path.join(assets, 'regular', n + '.svg'));
for (const n of duotone) out.duotone[n] = inner(path.join(assets, 'duotone', n + '-duotone.svg'));

fs.writeFileSync(new URL('../src/icons.mjs', import.meta.url),
  '// Phosphor Icons v2.1 (MIT, https://phosphoricons.com) — generated by tools/vendor-icons.mjs\n' +
  'export const ICONS = ' + JSON.stringify(out, null, 1) + ';\n');
console.log('icons:', regular.length, 'regular,', duotone.length, 'duotone');
