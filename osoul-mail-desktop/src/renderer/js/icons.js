const FILLED = new Set(['star']);

/**
 * بناء أيقونة.
 * @param {string} name  اسم الأيقونة
 * @param {string} extra أصناف CSS إضافية
 * @param {boolean} fill تعبئة الأيقونة (النجمة المفعّلة مثلًا)
 */
function icon(name, extra, fill) {
  const d = PATHS[name] || PATHS.info;
  const paths = d.split('|').map((p) => `<path d="${p}"/>`).join('');
  const fillAttr = fill && FILLED.has(name) ? 'currentColor' : 'none';
  return `<svg class="ic ${extra || ''}" viewBox="0 0 24 24" fill="${fillAttr}" stroke="currentColor"
    stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${paths}</svg>`;
}

/** أيقونة المجلد المناسبة حسب نوعه. */
function folderIcon(special) {
  return { inbox: 'inbox', sent: 'send', drafts: 'draft', trash: 'trash', junk: 'spam', archive: 'archive' }[special] || 'folder';
}

