  function paletteRender(q) {
    var box = qs('#osp-cmd-res'); if (!box) return;
    var ql = q.toLowerCase();
    var acts = paletteActions().filter(function (a) { return !ql || a.label.toLowerCase().indexOf(ql) !== -1; });
    var html = '', lastSec = '';
    acts.forEach(function (a, i) {
      if (a.sec !== lastSec) { html += '<div class="osp-cmd-sec">' + esc(a.sec) + '</div>'; lastSec = a.sec; }
      html += '<div class="osp-cmd-item" data-act="' + i + '">' + a.icon + '<b>' + esc(a.label) + '</b></div>';
    });
    box.innerHTML = html || ('<div class="osp-cmd-empty">' + t('لا نتائج مطابقة') + '</div>');
    qsa('[data-act]', box).forEach(function (el) {
      el.addEventListener('click', function () { acts[parseInt(el.getAttribute('data-act'), 10)].run(); });
    });
    // Live quote search for roles that use the admin/branch/rep quote detail.
    if (ql.length >= 2 && S.role !== 'partner') { paletteQuotes(q, box); }
  }
