  function bindEditor(q) {
    function recalc() {
      var sub = 0;
      qsa('.osp-price-row[data-i]').forEach(function (row) {
        var qty = parseFloat(qs('.pq', row).value) || 0;
        var pu = parseFloat(qs('.pu', row).value) || 0;
        var line = qty * pu;
        qs('.pl', row).textContent = num(line);
        sub += line;
      });
      var disc = parseFloat(qs('#ed-disc').value) || 0; if (disc > sub) disc = sub;
      var taxable = sub - disc, vat = taxable * 0.15, total = taxable + vat;
      qs('#ed-sub').textContent = num(sub); qs('#ed-d').textContent = num(disc);
      qs('#ed-vat').textContent = num(vat); qs('#ed-total').textContent = num(total) + ' ' + t('ر.س');
    }
    qsa('.pu').forEach(function (i) { i.addEventListener('input', recalc); });
    qs('#ed-disc').addEventListener('input', recalc);
    recalc();

    function collect(issue) {
      var prices = {};
      qsa('.osp-price-row[data-i]').forEach(function (row) {
        prices[row.getAttribute('data-i')] = parseFloat(qs('.pu', row).value) || 0;
      });
      return {
        id: q.id, prices: prices, issue: issue,
        discount: parseFloat(qs('#ed-disc').value) || 0,
        validity: parseInt(qs('#ed-val').value, 10) || 30,
        terms_ar: qs('#ed-tar').value, terms_en: qs('#ed-ten').value
      };
    }
    qs('#ed-save').addEventListener('click', function () { savePrice(collect(false), this); });
    qs('#ed-issue').addEventListener('click', function () {
      if (!confirm(t('تأكيد إصدار العرض؟ سيصبح متاحاً للإرسال للعميل.'))) return;
      savePrice(collect(true), this);
    });
  }
  function savePrice(body, btn) {
    btn.disabled = true; var o = btn.textContent; btn.textContent = '…';
    api('price', { method: 'POST', body: body }).then(function (q) {
      toast(body.issue ? t('تم إصدار العرض') : t('تم حفظ الأسعار'), 'ok');
      S.detail = q; renderDetail(q);
    }).catch(function (e) { toast(e.message, 'err'); btn.disabled = false; btn.textContent = o; });
  }

