  function pBindMake(q) {
    function recalc() {
      var sub = 0, prof = 0;
      qsa('.osp-price-row[data-i]').forEach(function (row) {
        var cost = parseFloat(row.getAttribute('data-cost')) || 0, qty = parseInt(row.getAttribute('data-qty'), 10) || 0;
        var sell = parseFloat(qs('.psell', row).value) || 0;
        qs('.pprofit', row).textContent = num((sell - cost) * qty);
        sub += sell * qty; prof += (sell - cost) * qty;
      });
      var disc = parseFloat(qs('#pc-disc').value) || 0; if (disc > sub) disc = sub;
      var taxable = sub - disc, vat = taxable * 0.15;
      qs('#p-sub').textContent = num(sub); qs('#p-vat').textContent = num(vat);
      qs('#p-tot').textContent = num(taxable + vat) + ' ' + t('ر.س'); qs('#p-prof').textContent = num(prof);
    }
    qsa('.psell').forEach(function (i) { i.addEventListener('input', recalc); });
    qs('#pc-disc').addEventListener('input', recalc);
    recalc();
    qs('#pc-issue').addEventListener('click', function () {
      var name = qs('#pc-name').value.trim();
      if (!name) { toast(t('أدخل اسم العميل'), 'err'); return; }
      var sell = {};
      qsa('.osp-price-row[data-i]').forEach(function (row) { sell[row.getAttribute('data-i')] = parseFloat(qs('.psell', row).value) || 0; });
      var btn = this; btn.disabled = true; btn.textContent = '…';
      api('p-quote', { method: 'POST', body: {
        supply_id: q.id, customer: { name: name, phone: qs('#pc-phone').value.trim(), email: qs('#pc-email').value.trim() },
        sell: sell, discount: parseFloat(qs('#pc-disc').value) || 0, validity: parseInt(qs('#pc-val').value, 10) || 30
      } }).then(function (d) { S.pNewQuote = d.url; toast(t('تم إصدار العرض ✓'), 'ok'); go('quotes'); })
        .catch(function (e) { toast(e.message, 'err'); btn.disabled = false; btn.textContent = t('إصدار العرض باسم شركتي'); });
    });
  }

