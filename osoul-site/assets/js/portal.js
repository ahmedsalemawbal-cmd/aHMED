  // Build the list chrome (tabs + search) once, then fill it. On poll refreshes
  // the search box is left untouched so typing/focus isn't disrupted.
  function renderChatList() {
    var box = qs('#chat-list'); if (!box) return;
    if (!qs('#chat-search')) {
      box.innerHTML =
        '<div class="osp-chat-filter">' +
          '<div class="osp-subtabs" id="chat-tabs"></div>' +
          '<input class="osp-input osp-chat-search" id="chat-search" type="search" placeholder="' + esc(t('بحث باسم المحادثة…')) + '" value="' + esc(S.chatSearch) + '">' +
        '</div>' +
        '<div class="osp-chat-threads" id="chat-threads"></div>';
      qs('#chat-search').addEventListener('input', function () { S.chatSearch = this.value.trim(); renderThreads(); });
    }
    renderChatTabs();
    renderThreads();
  }
  function renderChatTabs() {
    var tabsBox = qs('#chat-tabs'); if (!tabsBox) return;
    var all = S.chatThreads || [];
    var cnt = function (role) { return all.filter(function (x) { return x.role === role; }).length; };
    var defs = [
      { k: 'all', label: t('الكل'), n: all.length },
      { k: 'rep', label: t('المناديب'), n: cnt('rep') },
      { k: 'branch', label: t('الفروع'), n: cnt('branch') },
      { k: 'partner', label: t('الشركاء'), n: cnt('partner') },
      { k: 'customer', label: t('العملاء'), n: cnt('customer') }
    ].filter(function (d) { return d.k === 'all' || d.n > 0; });
    // If the active filter no longer has any threads, fall back to الكل.
    if (!defs.some(function (d) { return d.k === S.chatFilter; })) { S.chatFilter = 'all'; }
    tabsBox.innerHTML = defs.map(function (d) {
      return '<button class="osp-subtab' + (S.chatFilter === d.k ? ' active' : '') + '" data-cf="' + d.k + '">' +
        esc(d.label) + ' <span class="osp-cf-n">' + d.n + '</span></button>';
    }).join('');
    qsa('[data-cf]', tabsBox).forEach(function (b) {
      b.addEventListener('click', function () { S.chatFilter = b.getAttribute('data-cf'); renderChatTabs(); renderThreads(); });
    });
  }
  function renderThreads() {
    var box = qs('#chat-threads'); if (!box) return;
    var list = (S.chatThreads || []).slice();
    if (S.chatFilter && S.chatFilter !== 'all') { list = list.filter(function (x) { return x.role === S.chatFilter; }); }
    if (S.chatSearch) { var q = S.chatSearch.toLowerCase(); list = list.filter(function (x) { return (x.name || '').toLowerCase().indexOf(q) !== -1; }); }
    // Unread conversations float to the top, then most-recent activity.
    list.sort(function (a, b) { return ((b.unread > 0) - (a.unread > 0)) || ((b.last_ts || 0) - (a.last_ts || 0)); });
    if (!list.length) { box.innerHTML = '<div class="osp-empty" style="padding:26px 14px">' + t('لا توجد محادثات مطابقة.') + '</div>'; return; }
    box.innerHTML = list.map(threadItemHtml).join('');
    qsa('[data-thread]', box).forEach(function (el) {
      el.addEventListener('click', function () {
        openThread(parseInt(el.getAttribute('data-thread'), 10), el.getAttribute('data-name'), el.getAttribute('data-ava'));
      });
    });
  }
  function threadItemHtml(th) {
    var active = (th.id === S.chatThread) ? ' active' : '';
    return '<div class="osp-thread' + active + '" data-thread="' + th.id + '" data-name="' + esc(th.name) + '" data-ava="' + esc(th.avatar) + '">' +
      avatarHtml(th.avatar, th.name, 46) +
      '<div class="osp-thread-b"><div class="osp-thread-top"><b>' + esc(th.name) + '</b>' +
      '<span class="osp-tag ' + th.role + '">' + (roleName(th.role) || roleName('rep')) + '</span></div>' +
      '<span class="osp-thread-last">' + esc(th.last || t('لا رسائل بعد')) + '</span></div>' +
      (th.unread ? '<span class="osp-thread-unread">' + th.unread + '</span>' : '') + '</div>';
  }
  function openThread(id, name, ava) {
    S.chatThread = id; S.chatName = name; S.chatAvatar = ava;
    var wrap = qs('#chat-wrap'); if (wrap) wrap.classList.add('on-thread');
    qsa('[data-thread]').forEach(function (el) { el.classList.toggle('active', parseInt(el.getAttribute('data-thread'), 10) === id); });
    var act = qs('.osp-thread.active'); if (act) { var u = qs('.osp-thread-unread', act); if (u) u.remove(); }
    var main = qs('#chat-main'); if (main) main.innerHTML = conversationHtml();
    qs('#chat-head').innerHTML = chatHeadHtml();
    var back = qs('[data-cback]');
    if (back) back.addEventListener('click', function () {
      S.chatThread = 0; if (wrap) wrap.classList.remove('on-thread');
      qsa('[data-thread]').forEach(function (el) { el.classList.remove('active'); });
      if (main) main.innerHTML = chatEmpty();
    });
    bindComposer();
    loadMessages(true);
  }

