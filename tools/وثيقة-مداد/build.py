def screen(num, name, purpose, shows, actions, states=None, note=None):
    """شاشةٌ بعناوينها الأربعة الثابتة — والفارغة منها ليست حاشية."""
    D.h(2, 'ص-%s · %s' % (num, name))
    D.p('**الغرض:** ' + purpose)

    D.h(4, 'ما يظهر')
    D.bullet(shows)

    D.h(4, 'الأفعال')
    D.bullet(actions)

    if states:
        D.h(4, 'الحالات')
        D.bullet(states)

    if note:
        D.note(note)


