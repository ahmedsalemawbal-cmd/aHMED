-- ═══════════════════════════════════════════════════════════════════════════
-- ٠٠٠٨ — دلو الأصول يقبل ملفّات التصميم لا الـPDF وحدها
--
-- القالب المعتمد يُصمَّم في أداةٍ خارجيّة ويُصدَّر HTML. وكان الدلو يقبل
-- application/pdf وحده، فيُرفض ملفّ التصميم برسالةٍ من التخزين:
-- «mime type text/html is not supported».
--
-- ولا يُفتح الباب على مصراعيه: الدلو **خاصٌّ** بالمشرف، والأصل يُحفظ
-- للرجوع والمقارنة لا ليُعرض لأحد.
-- ═══════════════════════════════════════════════════════════════════════════

update storage.buckets
set allowed_mime_types = array['application/pdf', 'text/html', 'text/plain']
where id = 'template-sources';
