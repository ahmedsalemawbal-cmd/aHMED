-- ══ مفتاح الذكاء الاصطناعيّ ══
--
-- ويُفصل صفّان لا واحد، والفصلُ هو الأمان كلُّه:
--
--   `ai`        — المزوّد والنموذج وهل ضُبط. يقرؤه المالك ليرى الحالة.
--   `ai_secret` — المفتاح نفسه. **لا يقرؤه أحدٌ من متصفّح، ولا المالك.**
--
-- ولمَ يُمنع المالك من قراءة مفتاحه؟ لأنّ المفتاح إن بلغ المتصفّح مرّةً
-- صار عرضةً لكلّ ما يبلغ المتصفّح: إضافةٌ فضوليّة، أو سكربتٌ مدسوس، أو
-- شاشةٌ تُصوَّر. ولا حاجة به هناك أصلًا — الذي ينادي المزوّد هو الخادم.
--
--     ما لا يُقرأ لا يُسرَق.
--
-- والكتابة تبقى للمالك: يُبدّله متى شاء ولا يراه بعد أن يكتبه. ويرى في
-- `ai` أنّه مضبوطٌ وآخرَ أربعة أحرفٍ منه ليُميّز أيَّ مفتاحٍ وضع.

insert into public.platform_settings (key, value) values
  ('ai', jsonb_build_object(
      'provider', 'anthropic',
      'model', 'claude-sonnet-4-5',
      'configured', false,
      'hint', ''))
on conflict (key) do nothing;
